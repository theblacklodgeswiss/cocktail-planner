Future<List<String>> _defaultLoadCocktailNames() async {
  final data = await cocktailRepository.load();
  return data.recipes.map((r) => r.name).toList();
}

/// Opens the share sheet (formerly a fixed 700 px dialog): WhatsApp
/// message with a 14-day share link, editable bullet points, cocktail swap
/// and copy actions.
Future<void> showOfferShareSheet(
  BuildContext context, {
  required String clientName,
  required String editorName,
  required List<String> selectedCocktails,
  required Future<String> Function(List<String> bullets) createShareLink,
  Future<List<String>> Function() loadCocktailNames = _defaultLoadCocktailNames,
  ShareMiddleGenerator generateMiddle = defaultGenerateShareMiddle,
}) {
  return showAppSheet<void>(
    context,
    full: true,
    scrollable: true,
    builder: (_) => OfferShareSheet(
      clientName: clientName,
      editorName: editorName,
      selectedCocktails: selectedCocktails,
      createShareLink: createShareLink,
      loadCocktailNames: loadCocktailNames,
      generateMiddle: generateMiddle,
    ),
  );
}

/// Content of the share sheet. The middle "cocktail commentary" part of
/// the message is generated by Claude; the share link is created via
/// [createShareLink], appended to the message, copied and opened in
/// WhatsApp.
class OfferShareSheet extends StatefulWidget {
  const OfferShareSheet({
    super.key,
    required this.clientName,
    required this.editorName,
    required this.selectedCocktails,
    required this.createShareLink,
    this.loadCocktailNames = _defaultLoadCocktailNames,
    this.generateMiddle = defaultGenerateShareMiddle,
  });

  final String clientName;
  final String editorName;
  final List<String> selectedCocktails;

  /// Creates a 14-day share link for the offer snapshot with the given
  /// bullet points and returns its short code (see ShareLinkRepository).
  final Future<String> Function(List<String> bullets) createShareLink;
  final Future<List<String>> Function() loadCocktailNames;
  final ShareMiddleGenerator generateMiddle;

  @override
  State<OfferShareSheet> createState() => _OfferShareSheetState();
}

/// Default bullet points shown on the public link page, editable per
/// offer before sharing. One line per bullet.
const _defaultShareBullets =
    '5h unlimitiert Cocktails – mit und ohne Alkohol\n'
    'Harten Alkohol schenken wir kostenlos aus – du lieferst nur Flaschen & Mischgetränke\n'
    'Eine Bartheke bringen wir bei Bedarf kostenlos mit\n'
    'Becher, Eiswürfel, Strohhalme & Getränke bringen wir ebenfalls mit\n'
    'Bei Fragen melden wir uns gerne telefonisch';

class _OfferShareSheetState extends State<OfferShareSheet> {
  late final TextEditingController _messageCtrl;
  late final TextEditingController _bulletsCtrl;
  bool _loading = true;
  String? _error;
  bool _pdfSharing = false;
  bool _linkCopying = false;

  /// Reused by "copy link" and the WhatsApp button within one session.
  String? _cachedShareCode;

  /// Mutable copy of selectedCocktails, updated by the swap pickers.
  late List<String> _currentCocktails;
  List<String> _allCocktails = [];

  /// A cocktail was swapped but the message was not regenerated yet.
  bool _isDirty = false;

  @override
  void initState() {
    super.initState();
    _currentCocktails = List.from(widget.selectedCocktails);
    _messageCtrl = TextEditingController();
    _bulletsCtrl = TextEditingController(text: _defaultShareBullets)
      ..addListener(_invalidateCachedShareCode);
    _generate();
  }

  @override
  void dispose() {
    _bulletsCtrl.removeListener(_invalidateCachedShareCode);
    _messageCtrl.dispose();
    _bulletsCtrl.dispose();
    super.dispose();
  }

  void _invalidateCachedShareCode() => _cachedShareCode = null;

  List<String> get _bullets => _bulletsCtrl.text
      .split('\n')
      .map((line) => line.trim())
      .where((line) => line.isNotEmpty)
      .toList();

  static String _firstName(String name) {
    final trimmed = name.trim();
    return trimmed.isEmpty ? trimmed : trimmed.split(' ').first;
  }

  Future<void> _generate() async {
    setState(() {
      _loading = true;
      _error = null;
      _isDirty = false;
    });
    try {
      if (_allCocktails.isEmpty) {
        try {
          _allCocktails = await widget.loadCocktailNames();
        } catch (_) {
          // Continue without the full recipe list.
        }
      }
      final middlePart = await widget.generateMiddle(
        originalCocktails: widget.selectedCocktails,
        selectedCocktails: _currentCocktails,
        allAvailableCocktails: _allCocktails,
      );
      if (mounted) {
        setState(() {
          _messageCtrl.text = _buildMessage(middlePart);
          _loading = false;
        });
      }
    } catch (e) {
      if (mounted) {
        setState(() {
          _error = 'offer.share_generate_error'.tr();
          _loading = false;
        });
      }
    }
  }

  String _buildMessage(String? geminiMiddle) {
    final clientFirst = _firstName(widget.clientName).isNotEmpty
        ? _firstName(widget.clientName)
        : widget.clientName;
    final editorFirst = _firstName(widget.editorName).isNotEmpty
        ? _firstName(widget.editorName)
        : widget.editorName;

    final middle = (geminiMiddle != null && geminiMiddle.isNotEmpty)
        ? geminiMiddle
        : widget.selectedCocktails.isNotEmpty
        ? 'Wir haben uns die Auswahl angeschaut – ${widget.selectedCocktails.join(', ')} ist eine schöne Kombination!'
        : 'Wir haben dein Angebot basierend auf deiner Auswahl zusammengestellt.';

    return '''Hallo $clientFirst,

hier ist $editorFirst von Black Lodge! 😊

Wir haben dir das Angebot basierend auf deiner Auswahl erstellt. Hier noch ein kurzer Input von uns zum Mix:

$middle

Das Angebot ist ab heute 14 Tage gültig. Wenn das für dich so passt, gib uns kurz Bescheid, dann senden wir dir das Auftragsdokument für die Anzahlung zu.

Bei Fragen können wir gerne unter der Woche mal telefonieren.

Schönen Tag noch! 😊

Beste Grüße,
$editorFirst''';
  }

  void _snack(String key) {
    if (!mounted) return;
    ScaffoldMessenger.maybeOf(
      context,
    )?.showSnackBar(SnackBar(content: Text(key.tr())));
  }

  Future<void> _swap(int index) async {
    final picked = await showAppSheet<String>(
      context,
      builder: (sheet) {
        final p = AppPalette.of(sheet);
        return Column(
          mainAxisSize: MainAxisSize.min,
          crossAxisAlignment: CrossAxisAlignment.stretch,
          children: [
            Text(
              'offer.share_cocktail_selection'.tr(),
              style: AppText.heroTitle.copyWith(color: p.text),
            ),
            const SizedBox(height: AppSpace.s8),
            for (final name in _allCocktails)
              SelectCard(
                title: name,
                selected: name == _currentCocktails[index],
                onTap: () => Navigator.of(sheet).pop(name),
              ),
          ],
        );
      },
    );
    if (picked == null || !mounted) return;
    setState(() {
      _currentCocktails[index] = picked;
      _isDirty = true;
    });
  }

  Future<void> _copyToClipboard() async {
    await Clipboard.setData(ClipboardData(text: _messageCtrl.text));
    _snack('offer.share_copied');
  }

  Future<void> _openWhatsApp() async {
    final encoded = Uri.encodeComponent(_messageCtrl.text);
    final webUrl = Uri.parse('https://api.whatsapp.com/send?text=$encoded');
    if (await canLaunchUrl(webUrl)) {
      await launchUrl(webUrl, mode: LaunchMode.externalApplication);
    } else {
      _snack('offer.share_whatsapp_unavailable');
    }
  }

  Future<String> _ensureShareCode() async =>
      _cachedShareCode ??= await widget.createShareLink(_bullets);

  /// Copies just the raw link (creates it on first use).
  Future<void> _copyLinkOnly() async {
    setState(() => _linkCopying = true);
    try {
      final code = await _ensureShareCode();
      await Clipboard.setData(
        ClipboardData(text: '${Uri.base.origin}/s/$code'),
      );
      _snack('offer.share_link_copied');
    } catch (e) {
      _snack('offer.share_pdf_error');
    } finally {
      if (mounted) setState(() => _linkCopying = false);
    }
  }

  /// Message + link: copied and opened in WhatsApp.
  Future<void> _sharePdf() async {
    setState(() => _pdfSharing = true);
    try {
      final code = await _ensureShareCode();
      final fullMessage =
          '${_messageCtrl.text}\n\n${Uri.base.origin}/s/$code';
      await Clipboard.setData(ClipboardData(text: fullMessage));
      final webUrl = Uri.parse(
        'https://api.whatsapp.com/send?text=${Uri.encodeComponent(fullMessage)}',
      );
      if (await canLaunchUrl(webUrl)) {
        await launchUrl(webUrl, mode: LaunchMode.externalApplication);
      }
      _snack('offer.share_pdf_hint');
    } catch (e) {
      _snack('offer.share_pdf_error');
    } finally {
      if (mounted) setState(() => _pdfSharing = false);
    }
  }

  @override
  Widget build(BuildContext context) {
    final p = AppPalette.of(context);
    final busy = _loading || _pdfSharing;
    return Column(
      crossAxisAlignment: CrossAxisAlignment.stretch,
      children: [
        Text(
          'offer.share_title'.tr(),
          style: AppText.heroTitle.copyWith(color: p.text),
        ),
        const SizedBox(height: AppSpace.s16),
        Row(
          children: [
            Expanded(
              child: SecondaryButton(
                label: 'offer.copy_link'.tr(),
                loading: _linkCopying,
                onPressed: _linkCopying ? null : _copyLinkOnly,
              ),
            ),
            InfoButton(
              tooltip: 'offer.copy_link_info'.tr(),
              title: 'offer.copy_link_info'.tr(),
              message: 'offer.copy_link_info_message'.tr(),
            ),
          ],
        ),
        const SizedBox(height: AppSpace.s16),
        if (_loading)
          Padding(
            padding: const EdgeInsets.all(AppSpace.s24),
            child: Column(
              children: [
                const CircularProgressIndicator(),
                const SizedBox(height: AppSpace.s16),
                Text(
                  'offer.share_generating'.tr(),
                  style: AppText.body.copyWith(color: p.textSecondary),
                ),
              ],
            ),
          )
        else if (_error != null) ...[
          Text(_error!, style: AppText.body.copyWith(color: p.error)),
          const SizedBox(height: AppSpace.s16),
          SecondaryButton(label: 'common.retry'.tr(), onPressed: _generate),
          const SizedBox(height: AppSpace.s8),
          TextAction(
            label: 'common.close'.tr(),
            onPressed: () => Navigator.of(context).pop(),
          ),
        ] else ...[
          DocTextField(
            controller: _bulletsCtrl,
            label: 'offer.share_bullets_label'.tr(),
            minLines: 3,
            maxLines: null,
          ),
          const SizedBox(height: AppSpace.s4),
          Text(
            'offer.share_bullets_hint'.tr(),
            style: AppText.caption.copyWith(color: p.textSecondary),
          ),
          const SizedBox(height: AppSpace.s16),
          if (_allCocktails.isNotEmpty && _currentCocktails.isNotEmpty) ...[
            FieldLabel('offer.share_cocktail_selection'.tr()),
            PillGroup(
              children: [
                for (var i = 0; i < _currentCocktails.length; i++)
                  SelectPill(
                    label: _currentCocktails[i],
                    selected:
                        _currentCocktails[i] != widget.selectedCocktails[i],
                    icon: Icons.swap_horiz,
                    onTap: () => _swap(i),
                  ),
              ],
            ),
            const SizedBox(height: AppSpace.s8),
            SecondaryButton(
              label: _isDirty
                  ? 'offer.share_regenerate_hint'.tr()
                  : 'offer.share_regenerate'.tr(),
              onPressed: _pdfSharing ? null : _generate,
            ),
            const SizedBox(height: AppSpace.s16),
          ],
          DocTextField(
            controller: _messageCtrl,
            label: 'offer.share_message_label'.tr(),
            minLines: 6,
            maxLines: null,
          ),
          const SizedBox(height: AppSpace.s12),
          Text(
            'offer.share_pdf_tip'.tr(),
            style: AppText.caption.copyWith(color: p.textSecondary),
          ),
          const SizedBox(height: AppSpace.s16),
          PrimaryButton(
            label: 'offer.share_pdf'.tr(),
            loading: _pdfSharing,
            onPressed: busy ? null : _sharePdf,
          ),
          const SizedBox(height: AppSpace.s8),
          SecondaryButton(
            label: 'offer.share_whatsapp'.tr(),
            onPressed: busy ? null : _openWhatsApp,
          ),
          const SizedBox(height: AppSpace.s8),
          TextAction(
            label: 'offer.share_copy'.tr(),
            onPressed: busy ? null : _copyToClipboard,
          ),
        ],
      ],
    );
  }
}
